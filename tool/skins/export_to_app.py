"""Copy the generated skins into the app as a test build.

    COMFYUI_API_URL=https://comfyui.ol1n.com python3 tool/skins/export_to_app.py [--only id,id]

- duck: background cut out on ComfyUI (RMBG-2.0), cropped to the bird,
  centred on a square canvas so the longer side spans it, 256 px PNG
  -> assets/skins/duck/<id>.png (head at the bottom, as in SPRITES.md)
- bg: copied as is -> assets/skins/bg/<id>.jpg
- lib/game/skins/skin_catalog.dart: the list the game and the picker read
  (always every exported skin, also after an --only run)

Cut-outs are cached in tool/skins/out/cutout/, so a re-run only sends new ones.
"""

import argparse
import json
import shutil
import sys
import time
import uuid
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from catalog import PACKS  # noqa: E402
from generate import DEFAULT_ENV, Comfy, load_env  # noqa: E402

ROOT = HERE.parents[1]
OUT = HERE / "out"
CUT = OUT / "cutout"
ASSETS = ROOT / "assets" / "skins"
CATALOG = ROOT / "lib" / "game" / "skins" / "skin_catalog.dart"
SPRITE_PX = 256


def upload(comfy, path, name=None):
    """Upload to ComfyUI's input folder. Uploads overwrite by name, so files
    queued at the same time need distinct names (pass `name`)."""
    boundary = uuid.uuid4().hex
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"image\"; filename=\"kaceny_{name or path.name}\"\r\n"
        f"Content-Type: image/jpeg\r\n\r\n"
    ).encode() + path.read_bytes() + f"\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"overwrite\"\r\n\r\ntrue\r\n--{boundary}--\r\n".encode()
    import urllib.request
    headers = {k: v for k, v in comfy.headers.items() if k != "Content-Type"}
    headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
    req = urllib.request.Request(comfy.base + "/upload/image", data=body, headers=headers)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())["name"]


def cutout_graph(name, prefix):
    return {
        "1": {"class_type": "LoadImage", "inputs": {"image": name}},
        "2": {"class_type": "RMBG", "inputs": {"image": ["1", 0], "model": "RMBG-2.0", "sensitivity": 1.0,
                                                "process_res": 1024, "mask_blur": 0, "mask_offset": 0,
                                                "invert_output": False, "refine_foreground": True,
                                                "background": "Alpha", "background_color": "#222222"}},
        "3": {"class_type": "SaveImage", "inputs": {"filename_prefix": prefix, "images": ["2", 0]}},
    }


def cut_all(comfy, ids):
    CUT.mkdir(parents=True, exist_ok=True)
    pending = {}
    for sid in ids:
        if (CUT / f"{sid}.png").exists():
            continue
        name = upload(comfy, OUT / "duck" / f"{sid}.jpg")
        pending[comfy.submit(cutout_graph(name, f"kaceny_cut_{sid}"))] = sid
    print(f"cutting {len(pending)} ducks", flush=True)
    while pending:
        time.sleep(2)
        for pid in list(pending):
            img = comfy.result(pid)
            if img is None:
                continue
            (CUT / f"{pending[pid]}.png").write_bytes(comfy.download(img))
            print(f"  cut {pending.pop(pid)}", flush=True)


def sprite(src, dest):
    im = Image.open(src).convert("RGBA")
    box = im.getchannel("A").point(lambda a: 255 if a > 24 else 0).getbbox()
    if box is None:
        raise ValueError(f"{src.name}: nothing left after the cut-out")
    im = im.crop(box)
    side = max(im.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    canvas.resize((SPRITE_PX, SPRITE_PX), Image.LANCZOS).save(dest, optimize=True)


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def frame_count(sid):
    """Wing-beat frames exported for a skin (<id>_0.png, <id>_1.png, ...); 1 = the single sprite."""
    n = 0
    while (ASSETS / "duck" / f"{sid}_{n}.png").exists():
        n += 1
    return max(n, 1)


def all_styles():
    return [(pid, title, tier, sid, name)
            for pid, (title, tier, items) in PACKS.items() for sid, name, _, _ in items]


def write_all_catalog():
    """Every exported style, with its wing-beat frame count (animate.py / wan_frames.py)."""
    styles = [s for s in all_styles() if (ASSETS / "duck" / f"{s[3]}.png").exists()]
    lines = [
        "// GENERATED by tool/skins/export_to_app.py — do not edit by hand.",
        "",
        "import 'skin.dart';",
        "",
        "const generatedSkins = <Skin>[",
    ]
    for pack_id, pack_title, tier, sid, name in styles:
        lines.append(
            f"  Skin(id: {dart_str(sid)}, name: {dart_str(name)}, packId: {dart_str(pack_id)}, "
            f"packTitle: {dart_str(pack_title)}, free: {'true' if tier == 'free' else 'false'}"
            f"{f', frames: {frames}' if (frames := frame_count(sid)) > 1 else ''}),"
        )
    lines += ["];", ""]
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    CATALOG.write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", default=str(DEFAULT_ENV))
    ap.add_argument("--only", help="comma-separated style ids")
    args = ap.parse_args()
    load_env(args.env)

    styles = all_styles()
    if args.only:
        keep = set(args.only.split(","))
        styles = [s for s in styles if s[3] in keep]
    ids = [s[3] for s in styles]

    cut_all(Comfy(), ids)
    (ASSETS / "duck").mkdir(parents=True, exist_ok=True)
    (ASSETS / "bg").mkdir(parents=True, exist_ok=True)
    for sid in ids:
        sprite(CUT / f"{sid}.png", ASSETS / "duck" / f"{sid}.png")
        shutil.copyfile(OUT / "bg" / f"{sid}.jpg", ASSETS / "bg" / f"{sid}.jpg")
    write_all_catalog()
    print(f"exported {len(ids)} skins -> {ASSETS}, catalog -> {CATALOG}")


if __name__ == "__main__":
    main()
